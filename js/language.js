    function getSavedLanguage() {
        try {
            const saved = localStorage.getItem("omSaiLanguage");
            return Object.prototype.hasOwnProperty.call(translations, saved)
                ? saved
                : "en";
        } catch (error) {
            return "en";
        }
    }

    function applyLanguage(language) {
        if (!Object.prototype.hasOwnProperty.call(translations, language)) {
            language = "en";
        }

        const dictionary = translations[language];

        document.documentElement.lang = language;

        document.querySelectorAll("[data-i18n]").forEach(function (element) {
            const key = element.getAttribute("data-i18n");

            if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
                element.textContent = dictionary[key];
            }
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {
            const key = element.getAttribute("data-i18n-placeholder");

            if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
                element.placeholder = dictionary[key];
            }
        });

        document.querySelectorAll("[data-i18n-aria-label]").forEach(function (element) {
            const key = element.getAttribute("data-i18n-aria-label");

            if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
                element.setAttribute("aria-label", dictionary[key]);
            }
        });

        document.querySelectorAll("[data-language-selector]").forEach(function (selector) {
            selector.value = language;
        });

        try {
            localStorage.setItem("omSaiLanguage", language);
        } catch (error) {
            // Language selection still works if storage is unavailable.
        }
    }

    document.addEventListener("DOMContentLoaded", function () {
        document.querySelectorAll("[data-language-selector]").forEach(function (selector) {
            selector.addEventListener("change", function () {
                applyLanguage(selector.value);
            });
        });

        applyLanguage(getSavedLanguage());
    });

    window.omSaiApplyLanguage = applyLanguage;

